func TestQREncodeMatchesReference(t *testing.T) {
	for i, c := range qrRefCases {
		mod, err := qrEncode(c.text)
		if err != nil {
			t.Fatalf("case %d: %v", i, err)
		}
		if len(mod) != len(c.rows) {
			t.Fatalf("case %d: size %d != ref %d", i, len(mod), len(c.rows))
		}
		for y, row := range c.rows {
			for x, ch := range row {
				if got := mod[y][x]; got != (ch == '1') {
					t.Fatalf("case %d: module (%d,%d) mismatch", i, x, y)
				}
			}
		}
	}
}
